typedef struct DeviceRegExtension
{
    uint32_t ABI_VERSION;
    uint32_t STRUCT_SIZE;
    const char *KEY;
    const char *TYPE_NAME;
    void *VALUE;
    size_t VALUE_SIZE;
    struct DeviceRegExtension *NEXT;
} DeviceRegExtension;

typedef struct DeviceRegInfo
{
    uint32_t ABI_VERSION;
    uint32_t STRUCT_SIZE;
    DEVICE_MODEL_TYPE DEVICE_MODEL;
    uint32_t DEVICE_ID;
    const char *DEVICE_NAME;
    const char *DEVICE_LIBRARY;
    const char *DRIVER_ENTRY_POINT;
    const char *PARAMETER_SCHEMA;
    void *PARAMETER_DATA;
    size_t PARAMETER_DATA_SIZE;
    uint64_t CAPABILITY_FLAGS;
    DeviceRegExtension *EXTENSIONS;
    void *HOST_CONTEXT;
} DeviceRegInfo;
/* 
*   DeviceRegInfo负责注册设备的类型
*   在注册后可以被另一个函数自动地从相应的设备库中寻找到设备信息并对齐其参数。且
*   由于其参数不能完全确定，可能出现新的未知参数，对于这种未知参数，可以调用GPT进行
*   编码解决其对应的接口处理。
*   比如原有的模块没有热感应模块的注册函数，此时GPT会写出驱动并自动热重载注入代码，
*   实现接口的处理和应付。
*   !!!你仅仅需要实现这个结构体的原型，必须符合GPT能够热重载注入注册信息的要求!!!
*/


